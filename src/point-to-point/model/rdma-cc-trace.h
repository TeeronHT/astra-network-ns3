#ifndef RDMA_CC_TRACE_H
#define RDMA_CC_TRACE_H

#include <cstdint>
#include <cstdio>
#include <string>
#include <ns3/ptr.h>

namespace ns3 {

class RdmaQueuePair;

/*
 * Observational congestion-control trace and backend-wide counters.
 *
 * Nothing in here changes simulator behaviour. The trace is off unless the
 * frontend opens it (ENABLE_CCA_TRACE); the counters are plain integers that
 * the existing code paths increment after the fact.
 *
 * Trace modes:
 *   0  off
 *   1  state changes: QP_CREATE, MESSAGE_START, MESSAGE_COMPLETE, QP_DESTROY,
 *      RATE_DECREASE, RATE_INCREASE (timer / per-RTT increases), HPCC_UPDATE
 *      (full-RTT updates), DCTCP/TIMELY rate changes. Enough to rebuild the
 *      rate timeline of every QP; volume is per timer tick / RTT, not per packet.
 *   2  full: mode 1 plus per-packet feedback: CNP_RECEIVED, ECN_RECEIVED and
 *      HPCC_FAST_REACT (one record per event)
 *
 * Each record is one CSV line:
 *   time_ns,event,conn_id,qp_id,src,dst,sport,dport,cc_mode,rate_bps,
 *   target_rate_bps,alpha,hp_cur_rate_bps,window_bytes,snd_nxt,snd_una,
 *   size_bytes,extra
 * Fields that an algorithm does not use are written as their stored value
 * (0 or 1); readers should key on cc_mode.
 */
class RdmaCcTrace {
public:
	static int mode;
	static FILE* file;
	static uint32_t cc_mode;

	static void Open(const std::string& path, int trace_mode);
	static void Close();
	static inline bool On(int level) { return mode >= level && file != NULL; }

	// Record the QP's current controller state under `event`.
	static void Log(const char* event, Ptr<RdmaQueuePair> qp, uint64_t extra = 0);
	// Receiver-side event (no sender QP available). Node ids are ns-3 node ids.
	static void LogRx(const char* event, uint32_t node, uint32_t sip, uint32_t dip,
	                  uint16_t sport, uint16_t dport, uint64_t extra = 0);
};

struct RdmaCounters {
	static uint64_t ecn_marks;        // packets marked CE by switches
	static uint64_t cnp_acks;         // ACK/NACKs carrying the CNP flag received by NICs
	static uint64_t mmu_drops;        // ingress admission drops at switches
	static uint64_t pfc_pause_frames; // PAUSE frames generated by switches
	static uint64_t pfc_resume_frames;
	static uint64_t qps_created;
	static uint64_t qps_destroyed;
	static uint64_t messages_posted;    // work requests posted to any QP
	static uint64_t messages_completed; // work requests acknowledged
};

} // namespace ns3

#endif /* RDMA_CC_TRACE_H */
